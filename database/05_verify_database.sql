-- SCRIPT 05: VERIFY DATABASE
-- ============================================


-- 1. SHOW ALL TABLES
SELECT TABLE_NAME
FROM USER_TABLES
ORDER BY TABLE_NAME;


-- 2. COUNT TOTAL TABLES
SELECT COUNT(*) AS TOTAL_TABLES
FROM USER_TABLES;


-- 3. SHOW PRIMARY KEYS, FOREIGN KEYS,
-- UNIQUE AND CHECK CONSTRAINTS
SELECT
    TABLE_NAME,
    CONSTRAINT_NAME,
    CONSTRAINT_TYPE,
    STATUS
FROM USER_CONSTRAINTS
WHERE CONSTRAINT_TYPE IN ('P', 'R', 'U', 'C')
ORDER BY TABLE_NAME, CONSTRAINT_TYPE;


-- 4. SHOW ALL INDEXES
SELECT
    TABLE_NAME,
    INDEX_NAME,
    UNIQUENESS,
    STATUS
FROM USER_INDEXES
ORDER BY TABLE_NAME, INDEX_NAME;


-- 5. SHOW INITIAL ROLES
SELECT
    role_id,
    role_name,
    description
FROM ROLES
ORDER BY role_id;


-- 6. SHOW IDENTITY COLUMNS
SELECT
    TABLE_NAME,
    COLUMN_NAME,
    GENERATION_TYPE
FROM USER_TAB_IDENTITY_COLS
ORDER BY TABLE_NAME;


